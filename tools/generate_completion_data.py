"""Regenerate completion vocabulary from a local CUBRID manual Git reference."""

import argparse
from pathlib import Path
import pprint
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('manual', type=Path)
parser.add_argument('--ref', default='origin/release/11.4')
args = parser.parse_args()


def read(path):
  return subprocess.check_output(['git', '-C', str(args.manual), 'show', args.ref + ':' + path], text=True)


revision = subprocess.check_output(['git', '-C', str(args.manual), 'rev-parse', args.ref], text=True).strip()
config = read('en/admin/config.rst')
parameters = {}
for line in config.split('.. _lpg:')[0].splitlines():
  parts = [p.strip() for p in line.split('|')]
  if len(parts) == 9 and re.fullmatch(r'[a-z][a-z0-9_]+', parts[2]) and parts[5] in ('bool', 'int', 'float', 'string', 'byte', 'msec', 'sec'):
    parameters[parts[2]] = (parts[5], parts[7] in ('available', 'DBA only'), parts[7] == 'DBA only')

fields = {}
section = ''
lines = read('en/sql/query/show.rst').splitlines()
for i, line in enumerate(lines):
  if line.startswith('SHOW ') and i + 1 < len(lines) and re.fullmatch(r'[=-]+', lines[i + 1].strip()):
    section = line.strip()
    fields[section] = []
  match = re.match(r'^([A-Za-z_][A-Za-z_0-9]*)\s+(?:VARCHAR|CHAR|INT|BIGINT|NUMERIC|FLOAT|DOUBLE|SMALLINT|INTEGER|DATETIME|TIMESTAMP|DATE|TIME)(?:\(|\s|$)', line)
  if section and match and match[1] not in fields[section]:
    fields[section].append(match[1])
fields['SHOW TABLES'] = ['<tables>']
fields['SHOW FULL TABLES'] = ['<tables>', 'Owner', 'Table_type']
fields['SHOW FULL COLUMNS'] = fields['SHOW COLUMNS'] + ['Collation', 'Comment']
fields = {key: value for key, value in fields.items() if key in (
  'SHOW TABLES', 'SHOW FULL TABLES', 'SHOW COLUMNS', 'SHOW FULL COLUMNS',
  'SHOW ACCESS STATUS', 'SHOW THREADS', 'SHOW TRANSACTION TABLES',
)}
content = ('"""CUBRID 11.4 vocabulary generated by tools/generate_completion_data.py.\n\n'
           'Source: CUBRID/cubrid-manual@' + revision + '\n"""\n\n'
           '# Parameter name -> (type, dynamically changeable, requires DBA).\nPARAMETERS = ' + pprint.pformat(dict(sorted(parameters.items())), width=110, sort_dicts=False) + '\n\n'
           'SHOW_FIELDS = ' + pprint.pformat({k: tuple(v) for k, v in fields.items()}, width=110, sort_dicts=False) + '\n')
output = Path(__file__).resolve().parents[1] / 'src/csql_future/completion_data.py'
output.write_text(content, encoding='utf-8')
print(f'{len(parameters)} parameters; {len(fields)} SHOW field sets -> {output}')
